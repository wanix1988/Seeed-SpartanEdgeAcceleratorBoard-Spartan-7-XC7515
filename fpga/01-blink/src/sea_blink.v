`timescale 1ns / 1ps
// 仿真时间单位是 1 纳秒，精度是 1 皮秒。这只影响仿真器，不改变板上那颗 100 MHz 晶振。

// =============================================================================
// 入门实验 01：让一颗灯慢慢闪
//
// 这块 FPGA（XC7S15）上电后自己不会闪灯。我们用 Verilog 描述电路，Vivado 把它变成
// bitstream，再写进芯片。写进去之后，芯片里就是下面这个很小的电路，不再依赖电脑。
//
// 电路只有两样东西：
//   1. 一个每个时钟加 1 的计数器 div。
//   2. 把计数器的高位 div[24] 接到灯上。
//
// 为什么不把时钟直接接到灯上？
//   板载振荡器 X2 是 100 MHz，每秒跳 1 亿次，一次只有 10 纳秒。人眼看不出这么快的闪烁。
//   计数器的第 0 位每来一个时钟翻一次，第 1 位每 2 个时钟翻一次，第 n 位每 2^n 个时钟翻一次。
//   div[24] 每 2^24 = 16,777,216 个时钟翻一次。
//   两次翻转的间隔是 16,777,216 / 100,000,000 ≈ 0.168 秒。
//   亮一次再灭一次是两次翻转，周期是 2^25 个时钟 ≈ 0.336 秒，频率大约 3 Hz。
//
// 这些信号在时钟上升沿同时更新，所以它们是触发器，不是随时跟着变的导线。
//   <= 叫非阻塞赋值：先用旧值算出右边，再一起更新左边。
//   如果写成 =，同一段里后面的语句会看到前面已经改过的值，和真实触发器不一致。
//
// 灯怎么亮：
//   led 为 1 时引脚输出高电平。原理图里这根线接到绿色灯 D18 的阳极，所以 1 是亮、0 是灭。
//   引脚在约束文件 constrs/sea_blink.xdc 里：
//     clk 接封装脚 H4，来自 100 MHz 振荡器。
//     led 接封装脚 J1，也就是板上丝印 L1。
//   配置完成时这些触发器被清成 0，灯先灭，计数到 div[24] 变成 1 才第一次点亮。
// =============================================================================

module sea_blink (        // 模块是电路的边界，名字必须和 Vivado 工程的顶层一致
  input  wire clk,        // 输入时钟。wire 表示一根线，值由外部振荡器驱动，模块内部不保存它
  output reg  led         // 输出到灯。要在 always 里用 <= 赋值，语法上必须写成 reg；综合后它是触发器的输出
);                        // 端口表结束。上面两个信号就是这片电路和板子之间的全部连接
  reg [24:0] div;         // 25 位计数器，位号从 0 到 24。综合后是 25 个触发器，div[0] 是最低位

  always @(posedge clk) begin  // 只在 clk 从 0 变成 1 的那一刻执行下面两句，其余时间保持原值
    div <= div + 1'b1;         // 计数器加 1。1'b1 是“1 位二进制的 1”。加满后从 0 重新开始
    led <= div[24];            // 把第 24 位送给灯。这一拍用的仍是加 1 之前的旧值，所以灯比计数器慢一拍
  end                       // 上升沿动作结束。两个 <= 在同一个时钟沿一起生效

endmodule                  // 模块结束。Vivado 从这里综合出点灯电路
